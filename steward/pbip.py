"""Draft .PBIP export: the TMDL semantic model half (BUILD_PLAN N7 / C10). DRAFT: NOT OPENED IN POWER BI DESKTOP YET.

`export_pbip(spec, frames, out_dir)` writes a zip:

    <name>.pbip                              -> points at <name>.Report
    <name>.SemanticModel/definition.pbism    -> version 4.0 (TMDL allowed)
    <name>.SemanticModel/definition/         -> database.tmdl, model.tmdl, expressions.tmdl, relationships.tmdl, tables/*.tmdl
    <name>.Report/definition.pbir            -> byPath reference to the semantic model (report visuals come later)
    data/<entity>.csv                        -> the data the model reads (synthetic data from the data pack)
    spec.json, README.txt

Layout and syntax follow Microsoft's PBIP and TMDL docs (learn.microsoft.com/power-bi/developer/projects/projects-overview,
projects-dataset, projects-report; learn.microsoft.com/analysis-services/tmdl/tmdl-overview). Report visuals are not generated here.
Infeasible measures (gaps) are NOT written to the model: a gap must never become a number (lint rule DATA).
"""

from __future__ import annotations

import io
import json
import re
import uuid
import zipfile
from pathlib import Path

import pandas as pd

from .spec import DashboardSpec

PBIP_SCHEMA = "https://developer.microsoft.com/json-schemas/fabric/pbip/pbipProperties/1.0.0/schema.json"
PBISM_SCHEMA = "https://developer.microsoft.com/json-schemas/fabric/item/semanticModel/definitionProperties/1.0.0/schema.json"
PBIR_SCHEMA = "https://developer.microsoft.com/json-schemas/fabric/item/report/definitionProperties/2.0.0/schema.json"
COMPATIBILITY_LEVEL = 1567  # as in Microsoft's TMDL example
_QUOTE_CHARS = set(".=:' ")
README = """DRAFT, not opened in Power BI Desktop yet.

Generated by BI Steward from an approved dashboard spec. Contents:
- {name}.pbip, {name}.SemanticModel (TMDL semantic model), {name}.Report (only the link to the model; visuals are not generated yet)
- data/*.csv: synthetic data from the Bayer SinceAI 2026 data pack, not Bayer performance
- spec.json: the approved spec (KPI ids, lint result, provenance)

To open: unzip to a SHORT path (Windows limits paths to 260 characters), enable the PBIP, TMDL and PBIR preview features in
Power BI Desktop, then edit the DataFolder parameter in {name}.SemanticModel/definition/expressions.tmdl to the full path of the
unzipped data folder (Power Query cannot use relative file paths) and open {name}.pbip.
{gaps}"""


def _safe_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", name).strip("_")
    return (cleaned or "dashboard")[:40]  # short: PBIP paths are limited to 260 characters on Windows


def _q(name: str) -> str:
    """TMDL object names with a dot, equals, colon, quote or whitespace are single-quoted; quotes are doubled."""
    return "'" + name.replace("'", "''") + "'" if any(c in _QUOTE_CHARS for c in name) else name


def _dtype(series: pd.Series) -> tuple[str, str]:
    """(TMDL dataType, Power Query type)."""
    kind = series.dtype.kind
    if kind in "iu":
        return "int64", "Int64.Type"
    if kind == "f":
        return "double", "type number"
    if kind == "M":
        return "dateTime", "type datetime"
    if kind == "b":
        return "boolean", "type logical"
    return "string", "type text"


def _json(obj: dict) -> str:
    return json.dumps(obj, indent=2) + "\n"


def _measure_table(spec: DashboardSpec) -> str:
    """Measures live on the first fact entity (name starts with 'fact'), else on the first entity."""
    return next((e for e in spec.entities if e.startswith("fact")), spec.entities[0] if spec.entities else "")


def _table_tmdl(entity: str, frame: pd.DataFrame, columns: list[str], measures: list, keys: set[str]) -> str:
    lines = [f"table {_q(entity)}", ""]
    for m in measures:
        expression = " ".join(m.expression.split())  # one line DAX; multi-line is only needed for long expressions
        lines.append(f"\tmeasure {_q(m.name)} = {expression}")
        if m.format:
            lines.append(f"\t\tformatString: {m.format}")
        lines.append(f"\t\tdisplayFolder: {m.kpi_id}" if m.kpi_id else "\t\tdisplayFolder: Measures")
        lines.append("")
    types = []
    for column in columns:
        data_type, m_type = _dtype(frame[column])
        types.append(f'{{"{column}", {m_type}}}')
        lines += [f"\tcolumn {_q(column)}", f"\t\tdataType: {data_type}", f"\t\tsourceColumn: {column}", "\t\tsummarizeBy: none"]
        if column in keys:
            lines.append("\t\tisKey" if column.endswith("_id") and entity.startswith("dim") else "\t\tisHidden")
        lines.append("")
    lines += [
        f"\tpartition {_q(entity + '-Partition')} = m",
        "\t\tmode: import",
        "\t\tsource =",
        "\t\t\tlet",
        f'\t\t\t\tSource = Csv.Document(File.Contents(DataFolder & "\\{entity}.csv"), [Delimiter=",", Encoding=65001, QuoteStyle=QuoteStyle.Csv]),',
        "\t\t\t\tHeaders = Table.PromoteHeaders(Source, [PromoteAllScalars=true]),",
        f"\t\t\t\tTyped = Table.TransformColumnTypes(Headers, {{{', '.join(types)}}})",
        "\t\t\tin",
        "\t\t\t\tTyped",
        "",
    ]
    return "\n".join(lines)


def build_files(spec: DashboardSpec, frames: dict[str, pd.DataFrame]) -> dict[str, str]:
    """All text files of the project, path -> content. CSVs are added by `export_pbip`."""
    name = _safe_name(spec.name)
    sm, rp = f"{name}.SemanticModel", f"{name}.Report"
    entities = [e for e in spec.entities if e in frames]
    keys = {r.key for r in spec.relationships if r.key}
    buildable = [m for m in spec.measures if getattr(m, "feasible", True) and m.expression.strip()]
    gaps = [m for m in spec.measures if not getattr(m, "feasible", True)]
    home = _measure_table(spec)

    files: dict[str, str] = {
        f"{name}.pbip": _json({"$schema": PBIP_SCHEMA, "version": "1.0", "artifacts": [{"report": {"path": rp}}], "settings": {"enableAutoRecovery": True}}),
        f"{sm}/definition.pbism": _json({"$schema": PBISM_SCHEMA, "version": "4.0", "settings": {}}),
        f"{rp}/definition.pbir": _json({"$schema": PBIR_SCHEMA, "version": "4.0", "datasetReference": {"byPath": {"path": f"../{sm}"}}}),
        f"{sm}/definition/database.tmdl": f"database {_q(name)}\n\tcompatibilityLevel: {COMPATIBILITY_LEVEL}\n",
        f"{sm}/definition/model.tmdl": "model Model\n\tculture: en-US\n\tdefaultPowerBIDataSourceVersion: powerBI_V3\n\n"
        + "".join(f"ref table {_q(e)}\n" for e in entities),
        f"{sm}/definition/expressions.tmdl": 'expression DataFolder = "C:\\SinceAI\\data" meta [IsParameterQuery=true, Type="Text", IsParameterQueryRequired=true]\n'
        "\tlineageTag: 6e6f6c7a-0000-4000-8000-000000000001\n",
        "spec.json": spec.model_dump_json(indent=2) + "\n",
    }
    for entity in entities:
        wanted = spec.columns.get(entity) or list(frames[entity].columns)
        columns = [c for c in wanted if c in frames[entity].columns]
        measures = buildable if entity == home else []
        files[f"{sm}/definition/tables/{entity}.tmdl"] = _table_tmdl(entity, frames[entity], columns, measures, keys)

    relationships = []
    for rel in spec.relationships:
        if rel.from_entity in entities and rel.to_entity in entities and rel.key:
            rid = uuid.uuid5(uuid.NAMESPACE_URL, f"{name}:{rel.from_entity}:{rel.to_entity}:{rel.key}")
            relationships.append(
                f"relationship {rid}\n\tfromColumn: {_q(rel.from_entity)}.{_q(rel.key)}\n\ttoColumn: {_q(rel.to_entity)}.{_q(rel.key)}\n"
            )
    files[f"{sm}/definition/relationships.tmdl"] = "\n".join(relationships)
    gap_text = "".join(f"\nGap, not in the model: {m.name} ({m.kpi_id}): {getattr(m, 'gap_reason', '') or 'no governed source data'}" for m in gaps)
    files["README.txt"] = README.format(name=name, gaps=gap_text)
    return files


def export_pbip(spec: DashboardSpec, frames: dict[str, pd.DataFrame], out_dir: Path) -> Path:
    """Writes `<out_dir>/<name>.pbip.zip` and returns its path."""
    name = _safe_name(spec.name)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f"{name}.pbip.zip"
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as zf:
        for path, content in build_files(spec, frames).items():
            zf.writestr(path, content.encode("utf-8"))  # UTF-8 without BOM, as the docs require
        for entity in (e for e in spec.entities if e in frames):
            buffer = io.StringIO()
            frames[entity].to_csv(buffer, index=False)
            zf.writestr(f"data/{entity}.csv", buffer.getvalue().encode("utf-8"))
    return target
