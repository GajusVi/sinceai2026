"""Export a DashboardSpec as a Power BI project (.pbip): TMDL semantic model + PBIR report (BUILD_PLAN C10 / M4).

`export_pbip(spec, frames, out_dir)` writes `<name>.pbip.zip`:

    <name>.pbip
    <name>.SemanticModel/  definition.pbism, .platform, definition/{database,model,relationships}.tmdl, cultures/, tables/*.tmdl
    <name>.Report/         definition.pbir, .platform, StaticResources/ (theme), definition/{report,version}.json,
                           pages/pages.json, pages/<id>/page.json, pages/<id>/visuals/<id>/visual.json
    spec.json, README.txt

The format is copied from projects saved by Power BI Desktop 2.159 (templates/pbip/, see its README): never hand-written from memory.
`report.json`, `version.json` and the theme are copied verbatim from `templates/pbip/one_of_each`.
Data is embedded in each table's Power Query (compressed rows, the same encoding Desktop's "Enter data" uses), so the project
opens from any folder with no file path to edit. Infeasible measures (gaps) are never written: a gap must never become a number.
"""

from __future__ import annotations

import base64
import json
import re
import uuid
import zipfile
import zlib
from pathlib import Path

import pandas as pd

from .spec import DashboardSpec, Measure, Visual

TEMPLATE = Path(__file__).resolve().parents[1] / "templates" / "pbip" / "one_of_each" / "one_of_each.Report"
PBISM_VERSION = "4.2"  # as saved by Desktop 2.159
COMPATIBILITY_LEVEL = 1606  # as saved by Desktop 2.159
PAGE_W, PAGE_H, MARGIN, GAP = 1920, 1080, 20, 20
_QUOTE_CHARS = set(".=:' ")
# spec visual type -> (PBIR visualType, role of the dimension, role of the measures); only types present in the saved template
VISUALS = {
    "card": ("cardVisual", None, "Data"),
    "line": ("lineChart", "Category", "Y"),
    "bar": ("clusteredBarChart", "Category", "Y"),
    "table": ("tableEx", "Values", "Values"),
}
# spec dimension name -> (entity, column), first entity that is in the model wins
DIMENSIONS = {
    "month": [("dim_month", "month"), ("fact_pmm", "month")],
    "market": [("dim_market", "market_name")],
    "region": [("dim_market", "region")],
    "product": [("dim_product", "product_name")],
}
README = """Generated by BI Steward from an approved dashboard spec. Synthetic data from the Bayer SinceAI 2026 data pack, not Bayer performance.

To open: unzip to a SHORT path (Windows limits paths to 260 characters) and open {name}.pbip in Power BI Desktop
(version 2.159 or newer; the data is inside the model, there is nothing to configure). spec.json is the approved spec
(KPI ids, lint result, provenance).
{notes}"""


# -- small helpers -----------------------------------------------------------------------------------------------


def _safe_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", name).strip("_")
    return (cleaned or "dashboard")[:40]  # short: PBIP paths are limited to 260 characters on Windows


def _q(name: str) -> str:
    """TMDL object names with a dot, equals, colon, quote or whitespace are single-quoted; quotes are doubled."""
    return "'" + name.replace("'", "''") + "'" if any(c in _QUOTE_CHARS for c in name) else name


def _json(obj: dict) -> str:
    return json.dumps(obj, indent=2) + "\n"


def _uid(*parts: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, ":".join(parts)))


def _short_id(*parts: str) -> str:
    return uuid.uuid5(uuid.NAMESPACE_URL, ":".join(parts)).hex[:20]  # PBIR ids are 20 hex characters


def _format_string(fmt: str) -> str:
    """Spec formats carry a unit as plain text ('EUR M', '0.0 weeks'); Power BI wants literal text in quotes."""
    if not fmt or re.fullmatch(r"[#0,.%;\-]+", fmt):
        return fmt
    if fmt == "EUR M":
        return '#,0.0" EUR M"'
    number, _, unit = fmt.partition(" ")
    return f'{number}" {unit}"' if unit else fmt


# -- semantic model (TMDL) ---------------------------------------------------------------------------------------


def _dtype(series: pd.Series) -> tuple[str, str]:
    """(TMDL dataType, Power Query type)."""
    kind = series.dtype.kind
    if kind in "iu":
        return "int64", "Int64.Type"
    if kind == "f":
        return "double", "type number"
    if kind == "M":
        midnight = (series.dropna() == series.dropna().dt.normalize()).all()
        return "dateTime", "type date" if midnight else "type datetime"
    if kind == "b":
        return "boolean", "type logical"
    return "string", "type text"


def _cell(value):
    if value is None or (not isinstance(value, str) and pd.isna(value)):
        return None
    if isinstance(value, pd.Timestamp):
        return value.strftime("%Y-%m-%d") if value == value.normalize() else value.isoformat()
    if hasattr(value, "item"):  # numpy scalar
        return value.item()
    return value


def _embedded_rows(frame: pd.DataFrame, columns: list[str]) -> str:
    """Rows as compressed JSON text: raw deflate (what Power Query's Compression.Deflate reads), base64."""
    rows = [[_cell(v) for v in row] for row in frame[columns].itertuples(index=False, name=None)]
    packer = zlib.compressobj(9, zlib.DEFLATED, -15)
    raw = packer.compress(json.dumps(rows, separators=(",", ":"), allow_nan=False).encode("utf-8")) + packer.flush()
    return base64.b64encode(raw).decode("ascii")


def _m_text(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def _table_tmdl(entity: str, frame: pd.DataFrame, columns: list[str], measures: list[Measure], keys: set[str]) -> str:
    lines = [f"table {_q(entity)}", f"\tlineageTag: {_uid('table', entity)}", ""]
    for m in measures:
        expression = " ".join(m.expression.split())  # one line DAX
        lines.append(f"\tmeasure {_q(m.name)} = {expression}")
        if m.format:
            lines.append(f"\t\tformatString: {_format_string(m.format)}")
        lines.append(f"\t\tdisplayFolder: {m.kpi_id}" if m.kpi_id else "\t\tdisplayFolder: Reference")
        lines.append(f"\t\tlineageTag: {_uid('measure', entity, m.name)}")
        lines.append("")
    types = []
    for column in columns:
        data_type, m_type = _dtype(frame[column])
        types.append(f"{{{_m_text(column)}, {m_type}}}")
        lines += [f"\tcolumn {_q(column)}", f"\t\tdataType: {data_type}"]
        if data_type == "dateTime":
            lines.append("\t\tformatString: Long Date")
        lines += [f"\t\tlineageTag: {_uid('column', entity, column)}", "\t\tsummarizeBy: none", f"\t\tsourceColumn: {column}"]
        if column in keys:
            lines.append("\t\tisKey" if column.endswith("_id") and entity.startswith("dim") else "\t\tisHidden")
        if data_type == "dateTime":
            lines += ["", "\t\tannotation UnderlyingDateTimeDataType = Date"]
        lines.append("")
    names = ", ".join(_m_text(c) for c in columns)
    lines += [
        f"\tpartition {_q(entity)} = m",
        "\t\tmode: import",
        "\t\tsource =",
        "\t\t\t\tlet",
        f'\t\t\t\t    Source = Table.FromRows(Json.Document(Binary.Decompress(Binary.FromText("{_embedded_rows(frame, columns)}", BinaryEncoding.Base64), Compression.Deflate)), {{{names}}}),',
        f'\t\t\t\t    Typed = Table.TransformColumnTypes(Source, {{{", ".join(types)}}}, "en-US")',
        "\t\t\t\tin",
        "\t\t\t\t    Typed",
        "",
        "\tannotation PBI_ResultType = Table",
        "",
    ]
    return "\n".join(lines)


def _home(spec: DashboardSpec) -> str:
    """Measures live on the first fact entity (name starts with 'fact'), else on the first entity."""
    return next((e for e in spec.entities if e.startswith("fact")), spec.entities[0] if spec.entities else "")


def _prepare(frames: dict[str, pd.DataFrame]) -> dict[str, pd.DataFrame]:
    """The model must show the same numbers as the app: usage before an asset existed is a data-quality finding, left out."""
    out = dict(frames)
    if "fact_usage" in out and "dim_asset" in out and "created_date" in out["dim_asset"].columns:
        usage = out["fact_usage"].merge(out["dim_asset"][["asset_id", "created_date"]], on="asset_id", how="left")
        start = usage["created_date"].dt.to_period("M").dt.to_timestamp()
        out["fact_usage"] = usage[usage["month"] >= start].drop(columns=["created_date"])
    return out


def _model_files(
    spec: DashboardSpec, frames: dict[str, pd.DataFrame], name: str, measures: list[Measure]
) -> dict[str, str]:
    sm = f"{name}.SemanticModel"
    entities = [e for e in spec.entities if e in frames]
    keys = {r.key for r in spec.relationships if r.key}
    home = _home(spec)
    files = {
        f"{sm}/definition.pbism": _json({"version": PBISM_VERSION, "settings": {}}),
        f"{sm}/.platform": _platform("SemanticModel", name),
        f"{sm}/definition/database.tmdl": f"database\n\tcompatibilityLevel: {COMPATIBILITY_LEVEL}\n",
        f"{sm}/definition/model.tmdl": "model Model\n\tculture: en-US\n\tdefaultPowerBIDataSourceVersion: powerBI_V3\n"
        "\tsourceQueryCulture: en-US\n\tvalueFilterBehavior: independent\n\n"
        "annotation __PBI_TimeIntelligenceEnabled = 0\n\nannotation PBI_ProTooling = [\"DevMode\"]\n\n"
        + "".join(f"ref table {_q(e)}\n" for e in entities)
        + "ref cultureInfo en-US\n",
        f"{sm}/definition/cultures/en-US.tmdl": "cultureInfo en-US\n",
    }
    for entity in entities:
        wanted = spec.columns.get(entity) or list(frames[entity].columns)
        columns = [c for c in wanted if c in frames[entity].columns]
        files[f"{sm}/definition/tables/{entity}.tmdl"] = _table_tmdl(
            entity, frames[entity], columns, measures if entity == home else [], keys
        )
    relationships = []
    for rel in spec.relationships:
        if rel.from_entity in entities and rel.to_entity in entities and rel.key:
            relationships.append(
                f"relationship {_uid('relationship', name, rel.from_entity, rel.to_entity, rel.key)}\n"
                f"\tfromColumn: {_q(rel.from_entity)}.{_q(rel.key)}\n\ttoColumn: {_q(rel.to_entity)}.{_q(rel.key)}\n"
            )
    files[f"{sm}/definition/relationships.tmdl"] = "\n".join(relationships)
    return files


def _platform(kind: str, name: str) -> str:
    return _json(
        {
            "$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
            "metadata": {"type": kind, "displayName": name},
            "config": {"version": "2.0", "logicalId": _uid("logicalId", kind, name)},
        }
    )


# -- report (PBIR) -----------------------------------------------------------------------------------------------


def _template(rel: str) -> str:
    path = TEMPLATE / rel
    if not path.exists():
        raise FileNotFoundError(f"{path} is missing: save the Power BI Desktop templates first (templates/pbip/README.md)")
    return path.read_text(encoding="utf-8")


def _column(entity: str, prop: str, active: bool = False) -> dict:
    proj = {
        "field": {"Column": {"Expression": {"SourceRef": {"Entity": entity}}, "Property": prop}},
        "queryRef": f"{entity}.{prop}",
        "nativeQueryRef": prop,
    }
    if active:
        proj["active"] = True
    return proj


def _measure_ref(entity: str, name: str) -> dict:
    return {
        "field": {"Measure": {"Expression": {"SourceRef": {"Entity": entity}}, "Property": name}},
        "queryRef": f"{entity}.{name}",
        "nativeQueryRef": name,
    }


def _dimension(spec_dimension: str | None, entities: list[str]) -> tuple[str, str] | None:
    for entity, column in DIMENSIONS.get(spec_dimension or "", []):
        if entity in entities:
            return entity, column
    return None


def _layout(visuals: list[Visual]) -> list[tuple[int, int, int, int]]:
    """(x, y, width, height) per visual, same order. Cards in one row, charts two per row, tables full width."""
    boxes: list[tuple[int, int, int, int] | None] = [None] * len(visuals)
    y = MARGIN
    cards = [i for i, v in enumerate(visuals) if v.type == "card"]
    if cards:
        width = min(460, (PAGE_W - 2 * MARGIN - (len(cards) - 1) * GAP) // len(cards))
        for k, i in enumerate(cards):
            boxes[i] = (MARGIN + k * (width + GAP), y, width, 150)
        y += 150 + GAP
    charts = [i for i, v in enumerate(visuals) if v.type in ("line", "bar")]
    half = (PAGE_W - 2 * MARGIN - GAP) // 2
    for k, i in enumerate(charts):
        boxes[i] = (MARGIN + (k % 2) * (half + GAP), y, half, 380)
        if k % 2 == 1 or k == len(charts) - 1:
            y += 380 + GAP
    for i, v in enumerate(visuals):
        if boxes[i] is None:  # tables and anything else
            boxes[i] = (MARGIN, y, PAGE_W - 2 * MARGIN, 340)
            y += 340 + GAP
    return boxes  # type: ignore[return-value]


def _visual_json(spec: DashboardSpec, page: str, index: int, v: Visual, box, home: str, extra: dict[str, str]) -> dict | None:
    visual_type, dim_role, measure_role = VISUALS[v.type]
    x, y, w, h = box
    query: dict[str, dict] = {}
    if dim_role:
        found = _dimension(v.dimension, spec.entities)
        if found is None and v.type != "table":
            return None
        if found:
            query[dim_role] = {"projections": [_column(*found, active=v.type == "line")]}
    names = list(v.measures) + ([extra["forecast"]] if v.comparison == "forecast" and v.type == "line" and "forecast" in extra else [])
    projections = [_measure_ref(home, n) for n in names]
    if measure_role in query:  # table: dimension column and measures share the Values role
        query[measure_role]["projections"] += projections
    else:
        query[measure_role] = {"projections": projections}
    state: dict = {"queryState": query}
    if v.type == "line" and "Category" in query:
        state["sortDefinition"] = {
            "sort": [{"field": query["Category"]["projections"][0]["field"], "direction": "Ascending"}],
            "isDefaultSort": True,
        }
    return {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/visualContainer/2.14.0/schema.json",
        "name": _short_id("visual", spec.name, page, str(index)),
        "position": {"x": x, "y": y, "z": index * 1000, "height": h, "width": w, "tabOrder": index * 1000},
        "visual": {"visualType": visual_type, "query": state, "drillFilterOtherVisuals": True},
    }


def _report_files(spec: DashboardSpec, name: str, measures: list[Measure], extra: dict[str, str], notes: list[str]) -> dict[str, str]:
    rp = f"{name}.Report"
    home = _home(spec)
    gap_names = {m.name for m in spec.measures if not m.feasible or not m.expression.strip()}
    files = {
        f"{rp}/definition.pbir": _json({"version": "4.0", "datasetReference": {"byPath": {"path": f"../{name}.SemanticModel"}}}),
        f"{rp}/.platform": _platform("Report", name),
        f"{rp}/definition/report.json": _template("definition/report.json"),
        f"{rp}/definition/version.json": _template("definition/version.json"),
        f"{rp}/StaticResources/SharedResources/BaseThemes/Fluent2-CY26SU10.json": _template(
            "StaticResources/SharedResources/BaseThemes/Fluent2-CY26SU10.json"
        ),
    }
    order: list[str] = []
    for p_index, page in enumerate(spec.pages):
        page_id = _short_id("page", spec.name, str(p_index))
        order.append(page_id)
        keep: list[Visual] = []
        for v in page.visuals:
            if v.type not in VISUALS:
                notes.append(f'Visual "{v.title}" ({v.type}) is not exported: no saved Desktop template for that type.')
            elif any(n in gap_names for n in v.measures):
                notes.append(f'Visual "{v.title}" is not exported: it needs a governed gap (no source data), shown as a gap in the app.')
            else:
                keep.append(v)
        boxes = _layout(keep)
        height = max(PAGE_H, max((y + h for _, y, _, h in boxes), default=0) + MARGIN)
        files[f"{rp}/definition/pages/{page_id}/page.json"] = _json(
            {
                "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/page/2.1.0/schema.json",
                "name": page_id,
                "displayName": page.name,
                "displayOption": "FitToPage",
                "height": height,
                "width": PAGE_W,
            }
        )
        for i, (v, box) in enumerate(zip(keep, boxes)):
            body = _visual_json(spec, page_id, i, v, box, home, extra)
            if body is None:
                notes.append(f'Visual "{v.title}" is not exported: dimension "{v.dimension}" is not in the model.')
                continue
            files[f"{rp}/definition/pages/{page_id}/visuals/{body['name']}/visual.json"] = _json(body)
    files[f"{rp}/definition/pages/pages.json"] = _json(
        {
            "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/pagesMetadata/1.1.0/schema.json",
            "pageOrder": order,
            "activePageName": order[0] if order else "",
        }
    )
    return files


# -- public ------------------------------------------------------------------------------------------------------


def build_files(spec: DashboardSpec, frames: dict[str, pd.DataFrame]) -> dict[str, str]:
    """All files of the project, path -> text content."""
    name = _safe_name(spec.name)
    frames = _prepare(frames)
    buildable = [m for m in spec.measures if m.feasible and m.expression.strip()]
    gaps = [m for m in spec.measures if not m.feasible]
    extra: dict[str, str] = {}
    home = _home(spec)
    uses_forecast = any(v.comparison == "forecast" and v.type == "line" for p in spec.pages for v in p.visuals)
    if uses_forecast and home in frames and "forecast_m_eur_syn" in frames[home].columns:
        reference = Measure(
            name="Forecast", kpi_id="", expression=f"SUM({home}[forecast_m_eur_syn])", format="EUR M", unit="EUR"
        )
        buildable = buildable + [reference]
        extra["forecast"] = reference.name
    notes = [
        f"Gap, not in the model: {m.name} ({m.kpi_id}): {m.gap_reason or 'no governed source data'}" for m in gaps
    ]
    files = {
        f"{name}.pbip": _json(
            {"version": "1.0", "artifacts": [{"report": {"path": f"{name}.Report"}}], "settings": {"enableAutoRecovery": True}}
        ),
        "spec.json": spec.model_dump_json(indent=2) + "\n",
    }
    files.update(_model_files(spec, frames, name, buildable))
    files.update(_report_files(spec, name, buildable, extra, notes))
    files["README.txt"] = README.format(name=name, notes="".join(f"\n- {n}" for n in notes))
    return files


def export_pbip(spec: DashboardSpec, frames: dict[str, pd.DataFrame], out_dir: Path) -> Path:
    """Writes `<out_dir>/<name>.pbip.zip` and returns its path."""
    name = _safe_name(spec.name)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f"{name}.pbip.zip"
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as zf:
        for path, content in build_files(spec, frames).items():
            zf.writestr(path, content.encode("utf-8"))  # UTF-8 without BOM, as the docs require
    return target
